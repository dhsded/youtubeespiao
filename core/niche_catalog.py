def get_available_niches() -> List[str]:
    """Retorna a lista formatada de todos os grandes nichos disponíveis."""
    return list(NICHE_CATALOG.keys())


def get_subniches_for_niche(niche_name: str) -> List[str]:
    """Retorna os subnichos cadastrados para o nicho informado."""
    if niche_name in NICHE_CATALOG:
        return list(NICHE_CATALOG[niche_name]["subniches"].keys())
    return []


def generate_queries_for_subniche(
    niche_name: str,
    subniche_name: str,
    additional_keyword: Optional[str] = None
) -> List[str]:
    """
    Gera as consultas de busca estruturadas para um subnicho específico.
    Se fornecida uma palavra adicional (opcional), combina aos termos base.
    """
    queries = []
    if niche_name in NICHE_CATALOG:
        sub_dict = NICHE_CATALOG[niche_name]["subniches"]
        if subniche_name in sub_dict:
            base_queries = list(sub_dict[subniche_name])
            if additional_keyword and additional_keyword.strip():
                clean_add = additional_keyword.strip().lower()
                for bq in base_queries:
                    queries.append(f"{bq} {clean_add}")
            else:
                queries.extend(base_queries)
    return queries


def get_all_subniches_flat() -> List[Dict[str, Any]]:
    """Retorna todos os nichos e subnichos em uma lista plana para varredura global."""
    flat_list = []
    for n_name, n_data in NICHE_CATALOG.items():
        for s_name, q_list in n_data["subniches"].items():
            flat_list.append({
                "niche": n_name,
                "subniche": s_name,
                "queries": list(q_list)
            })
    return flat_list
